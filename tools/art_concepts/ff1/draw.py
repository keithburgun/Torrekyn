def render(name, Z=8):
    pal, txt = S[name]
    rows = [r for r in txt.strip('\n').split('\n')]
    w = max(len(r) for r in rows); h = len(rows)
    cols = {'d': hx(pal[0]), 'm': hx(pal[1]), 'l': hx(pal[2])}
    im = Image.new('RGB', (w + 8, h + 8), BG); p = im.load()
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c in cols: p[x + 4, y + 4] = cols[c]
    return im
